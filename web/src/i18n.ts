const dictionaries = { zh, en };

export type Key = keyof typeof zh;

export function translate(locale: Locale, key: Key, vars?: Record<string, string | number>): string {
  let text: string = dictionaries[locale][key] ?? dictionaries.zh[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function greetingKey(date = new Date()): Key {
  const hour = date.getHours();
  if (hour < 5) return "greetLate";
  if (hour < 11) return "greetMorning";
  if (hour < 14) return "greetNoon";
  if (hour < 18) return "greetAfternoon";
  return "greetEvening";
}

export function dayBucket(iso: string, now = new Date()): "today" | "yesterday" | "earlier" {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "earlier";
  const start = (value: Date) => new Date(value.getFullYear(), value.getMonth(), value.getDate()).getTime();
  const diff = start(now) - start(date);
  if (diff <= 0) return "today";
  if (diff === 86_400_000) return "yesterday";
  return "earlier";
}

export function formatWhen(iso: string, locale: Locale): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return new Intl.DateTimeFormat(locale === "zh" ? "zh-CN" : "en", {
    month: "numeric",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
}

export function formatNumber(value: number, locale: Locale): string {
  return new Intl.NumberFormat(locale === "zh" ? "zh-CN" : "en").format(value);
}
